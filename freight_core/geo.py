def nearest_hub(city: str | None, *, max_km: float = 120.0) -> str | None:
    """Map a village/suburb to the nearest major hub within max_km."""
    pt = city_point(city)
    if not pt:
        return None
    n = (city or "").lower().replace("ё", "е").strip()
    if n in MAJOR_HUBS:
        return n
    best_name: str | None = None
    best_d = 1e9
    for h in MAJOR_HUBS:
        hp = city_point(h)
        if not hp:
            continue
        d = haversine_km(pt, hp)
        if d < best_d:
            best_d = d
            best_name = h
    if best_name is not None and best_d <= float(max_km):
        return best_name
    return None


def geo_filter(
    *,
    base: str | None,
    from_city: str | None,
    to_city: str | None,
    radius_km: float | None,
    backhaul_only: bool,
    far_radius_km: float | None = None,
) -> tuple[bool, str, list[str]]:
    """
    Return (ok, reason, matched_tags).

    Normal mode (Moscow carrier use-case):
      - one endpoint within ``radius_km`` of base (near hub, e.g. 150 km)
      - BOTH endpoints within ``far_radius_km`` of base (e.g. 1500 km) —
        neither loading nor unloading may be farther than that
      - either direction: near→far or far→near

    Equivalent when both ends are geocoded:
      min(d_from, d_to) ≤ radius_km  AND  max(d_from, d_to) ≤ far_radius_km

    If only one end is known: it must be ≤ far_radius_km (never accept >1500 km).

    backhaul_only: unload (to) must be near base (ignores far radius).
    """
    matched: list[str] = []
    base_n = (base or "").lower().strip() or None
    if not base_n:
        return True, "no_base", matched

    if backhaul_only:
        if not to_city:
            return False, "backhaul_no_to", matched
        d = distance_km(to_city, base_n)
        if d is None:
            if base_n in to_city or to_city in base_n:
                matched.append("обратка≈база")
                return True, "ok", matched
            return False, "backhaul_unknown_geo", matched
        if d <= max(80.0, (radius_km or 80.0)):
            matched.append(f"обратка {d:.0f}км")
            return True, "ok", matched
        return False, "not_backhaul", matched

    if radius_km is None:
        return True, "no_radius", matched

    far_r = far_radius_km if far_radius_km is not None else max(float(radius_km), 1500.0)

    if not from_city and not to_city:
        return False, "no_route", matched

    def _dist(city: str | None) -> float | None:
        if not city:
            return None
        d = distance_km(city, base_n)
        if d is not None:
            return d
        # fuzzy: base name contained in city string
        if base_n in city or city in base_n:
            return 0.0
        return None

    d_from = _dist(from_city)
    d_to = _dist(to_city)

    # Hard rule: no known endpoint may exceed far radius from base
    for label, d in (("погрузка", d_from), ("выгрузка", d_to)):
        if d is not None and d > far_r:
            return False, "outside_far_radius", matched

    if d_from is not None and d_to is not None:
        near_d, far_d = (d_from, d_to) if d_from <= d_to else (d_to, d_from)
        near_label = "погрузка" if d_from <= d_to else "выгрузка"
        far_label = "выгрузка" if d_from <= d_to else "погрузка"
        if near_d <= radius_km and far_d <= far_r:
            matched.append(f"{near_label} {near_d:.0f}км≤{radius_km:g}")
            matched.append(f"{far_label} {far_d:.0f}км≤{far_r:g}")
            return True, "ok", matched
        if near_d > radius_km:
            return False, "no_near_leg", matched
        return False, "far_leg_too_far", matched

    # Only one end geocoded: accept only if it is near the base.
    # Far single-end or unknown second city → reject (cannot prove corridor).
    known = d_from if d_from is not None else d_to
    if known is not None:
        label = "погрузка" if d_from is not None else "выгрузка"
        if known <= radius_km:
            # Still reject: need both ends for corridor (user wants strict near+far).
            return False, "incomplete_route", matched
        return False, "no_near_leg", matched

    return False, "geo_unknown", matched


def parse_profile_geo(profile: dict[str, Any]) -> tuple[float | None, float | None, bool]:
    """Return (near_radius_km, far_radius_km, backhaul_only)."""
    radius = profile.get("radius") or profile.get("radius_km")
    far = profile.get("radius_far") or profile.get("far_radius") or profile.get("far_radius_km")
    try:
        radius_f = float(radius) if radius not in (None, "") else None
    except (TypeError, ValueError):
        radius_f = None
    try:
        far_f = float(far) if far not in (None, "") else None
    except (TypeError, ValueError):
        far_f = None
    if radius_f is not None and far_f is None:
        far_f = 1500.0
    backhaul = str(profile.get("backhaul") or profile.get("backhaul_only") or "").lower() in {
        "1",
        "true",
        "yes",
        "on",
        "да",
    }
    return radius_f, far_f, backhaul
